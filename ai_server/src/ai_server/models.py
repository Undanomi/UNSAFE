class MachineInformation(BaseModel):
    name: str = Field(min_length=1, max_length=40)
    visibility: Literal["private", "public", "非公開", "公開"]
    theme: str = Field(min_length=1, max_length=500)
    difficulty: Literal["Very Easy", "Easy", "Medium", "High"]
    operating_system: str = Field(default="Debian 13.7.0", min_length=1, max_length=100)
    needs_user_flag: bool | None = None
    user_flag_details: str = Field(default="", max_length=4000)
    needs_system_flag: bool | None = None
    system_flag_details: str = Field(default="", max_length=4000)
    skill_names: (
        list[Annotated[str, Field(pattern=r"^[a-z0-9]+(?:-[a-z0-9]+)*$", max_length=64)]] | None
    ) = Field(default=None, max_length=32)
    cve_ids: list[Annotated[str, Field(pattern=r"^CVE-\d{4}-\d{4,7}$")]] = Field(
        default_factory=list, max_length=20
    )

    @model_validator(mode="before")
    @classmethod
    def promote_flag_detail_cves(cls, value):
        if not isinstance(value, dict):
            return value
        normalized = dict(value)
        explicit = list(normalized.get("cve_ids") or [])
        seen = set(explicit)
        for field_name in ("user_flag_details", "system_flag_details"):
            details = str(normalized.get(field_name) or "")
            for cve_id in re.findall(r"CVE-\d{4}-\d{4,7}", details, re.IGNORECASE):
                canonical = cve_id.upper()
                if canonical not in seen:
                    explicit.append(canonical)
                    seen.add(canonical)
        normalized["cve_ids"] = explicit
        return normalized

    @field_validator("skill_names", "cve_ids")
    @classmethod
    def unique_skill_choices(cls, values):
        if values is not None and len(values) != len(set(values)):
            raise ValueError("Skill names and CVE IDs must not contain duplicates")
        return values

    @field_validator("operating_system", mode="before")
    @classmethod
    def default_operating_system(cls, value):
        if value is None or not str(value).strip():
            return "Debian 13.7.0"
        value = str(value).strip()
        match = re.fullmatch(r"debian\s+(\d+(?:\.\d+){0,2})", value, re.IGNORECASE)
        if not match:
            raise ValueError("Only versioned Debian base images are supported (e.g. Debian 13.7.0)")
        return f"Debian {match.group(1)}"

    @model_validator(mode="after")
    def validate_flag_details(self) -> MachineInformation:
        if self.needs_user_flag is True and not self.user_flag_details.strip():
            raise ValueError("user_flag_details is required when needs_user_flag is true")
        if self.needs_system_flag is True and not self.system_flag_details.strip():
            raise ValueError("system_flag_details is required when needs_system_flag is true")
        for field_name, details in (
            ("user_flag_details", self.user_flag_details),
            ("system_flag_details", self.system_flag_details),
        ):
            stripped = details.strip()
            if re.fullmatch(r"flag\{[^{}]+\}", stripped, re.IGNORECASE):
                raise ValueError(
                    f"{field_name} describes acquisition requirements; flag values are "
                    "generated by the server"
                )
        return self


