class PasswordCrackingSpec(BaseModel):
    wordlist: Literal["rockyou.txt"]
    password: str | None = Field(
        default=None, min_length=8, max_length=32, pattern=r"^[A-Za-z0-9]+$"
    )
    line_number: int | None = Field(default=None, ge=1)
    search_space_lines: int | None = Field(default=None, ge=1)
    hash_algorithm: str = Field(min_length=1, max_length=100)
    hash_runtime: str = Field(min_length=1, max_length=100)
    hash_api: str = Field(min_length=1, max_length=200)
    hashcat_mode: int | None = Field(default=None, ge=0)
    john_format: str | None = Field(default=None, min_length=1, max_length=100)
    target_crack_seconds: int = Field(ge=120, le=180)

    @model_validator(mode="after")
    def validate_cracking_parameters(self) -> PasswordCrackingSpec:
        selection = (self.password, self.line_number, self.search_space_lines)
        if any(value is None for value in selection) and any(
            value is not None for value in selection
        ):
            raise ValueError(
                "rockyou selection fields must be all unset or all populated"
            )
        if (
            self.line_number is not None
            and self.search_space_lines is not None
            and self.line_number > self.search_space_lines
        ):
            raise ValueError("password line must be within the declared search space")
        if self.hashcat_mode is None and self.john_format is None:
            raise ValueError("password cracking requires a Hashcat mode or John format")
        return self

    @property
    def selection_bound(self) -> bool:
        return self.password is not None


class AttackStep(BaseModel):
    step_id: str = Field(pattern=r"^[a-z][a-z0-9_-]{0,63}$")
    title: str = Field(min_length=1, max_length=200)
    kind: str = Field(min_length=1, max_length=64)
    phase: str = Field(min_length=1, max_length=64)
    description: str = Field(min_length=1, max_length=4000)
    requires: list[str] = Field(default_factory=list, max_length=20)
    achieves: list[str] = Field(default_factory=list, max_length=10)
    cve_id: str | None = Field(default=None, pattern=r"^CVE-\d{4}-\d{4,7}$")
    cve_title: str | None = Field(default=None, max_length=500)
    cve_description: str | None = Field(default=None, max_length=4000)
    cwe_ids: list[str] = Field(default_factory=list, max_length=30)
    installation_artifact: (
        Literal[
            "os_repository_package",
            "vendor_repository_package",
            "vendor_release_binary",
            "other_prebuilt",
            "source_build",
        ]
        | None
    ) = None
    artifact_source: str | None = Field(default=None, max_length=1000)
    source_build_reason: str | None = Field(default=None, max_length=2000)
    software: str | None = Field(default=None, max_length=200)
    vulnerable_version: str | None = Field(default=None, max_length=200)
    os_compatible: bool | None = None
    compatibility_reason: str | None = Field(default=None, max_length=2000)
    installation_method: str | None = Field(default=None, max_length=500)
    implementation_steps: list[str] = Field(min_length=1, max_length=50)
    references: list[str] = Field(default_factory=list, max_length=30)
    password_cracking: PasswordCrackingSpec | None = None

    @model_validator(mode="after")
    def validate_cve_fields(self) -> AttackStep:
        if self.kind == "cve" and not self.cve_id:
            raise ValueError("a cve attack step requires cve_id")
        if self.kind != "cve" and self.cve_id:
            raise ValueError("cve_id is only valid when kind is cve")
        if self.kind != "cve" and (self.cve_title or self.cve_description or self.cwe_ids):
            raise ValueError("official CVE facts are only valid when kind is cve")
        if self.kind != "cve" and (
            self.installation_artifact or self.artifact_source or self.source_build_reason
        ):
            raise ValueError("CVE installation evidence is only valid when kind is cve")
        if self.installation_artifact == "source_build" and not self.source_build_reason:
            raise ValueError("source-built CVE software requires a source_build_reason")
        if self.kind == "password_cracking" and self.password_cracking is None:
            raise ValueError("a password_cracking step requires password_cracking metadata")
        if self.kind != "password_cracking" and self.password_cracking is not None:
            raise ValueError(
                "password_cracking metadata is only valid when kind is password_cracking"
            )
        return self


class AttackGraph(BaseModel):
    objectives: list[AttackObjective] = Field(default_factory=list, max_length=10)
    steps: list[AttackStep] = Field(min_length=1, max_length=30)

    @model_validator(mode="after")
    def validate_graph(self) -> AttackGraph:
        objective_ids = [objective.objective_id for objective in self.objectives]
        if len(objective_ids) != len(set(objective_ids)):
            raise ValueError("attack objective IDs must be unique")
        objective_types = [objective.objective_type for objective in self.objectives]
        if len(objective_types) != len(set(objective_types)):
            raise ValueError("attack objective types must be unique")

        step_ids = [step.step_id for step in self.steps]
        if len(step_ids) != len(set(step_ids)):
            raise ValueError("attack step IDs must be unique")
        known_steps = set(step_ids)
        known_objectives = set(objective_ids)
        for step in self.steps:
            if len(step.requires) != len(set(step.requires)):
                raise ValueError(f"attack step {step.step_id} has duplicate requirements")
            if len(step.achieves) != len(set(step.achieves)):
                raise ValueError(f"attack step {step.step_id} has duplicate objectives")
            if step.step_id in step.requires:
                raise ValueError(f"attack step {step.step_id} cannot require itself")
            unknown_steps = set(step.requires) - known_steps
            if unknown_steps:
                raise ValueError(
                    f"attack step {step.step_id} has unknown requirements: {sorted(unknown_steps)}"
                )
            unknown_objectives = set(step.achieves) - known_objectives
            if unknown_objectives:
                raise ValueError(
                    f"attack step {step.step_id} has unknown objectives: "
                    f"{sorted(unknown_objectives)}"
                )

        self._validate_acyclic_graph()
        achieved = {objective for step in self.steps for objective in step.achieves}
        missing = known_objectives - achieved
        if missing:
            raise ValueError(f"attack objectives are not achieved by any step: {sorted(missing)}")
        return self

    def _validate_acyclic_graph(self) -> None:
        dependencies = {step.step_id: step.requires for step in self.steps}
        visiting: set[str] = set()
        visited: set[str] = set()

        def visit(step_id: str) -> None:
            if step_id in visiting:
                raise ValueError(f"attack graph contains a cycle at {step_id}")
            if step_id in visited:
                return
            visiting.add(step_id)
            for dependency in dependencies[step_id]:
                visit(dependency)
            visiting.remove(step_id)
            visited.add(step_id)

        for step_id in dependencies:
            visit(step_id)


class ScenarioDraft(BaseModel):
    scenario_id: str
    scenario_version_id: str = "v1"
    title: str
    scenario_description: str = Field(default="", max_length=1000)
    definition: str = Field(min_length=1, max_length=SCENARIO_DEFINITION_MAX_CHARS)
    target_os: str = "Debian 13.7.0"
    attack_graph: AttackGraph
    user_flag: str | None = Field(
        default=None,
        min_length=22,
        max_length=134,
        pattern=r"^flag\{[A-Za-z0-9][A-Za-z0-9_-]{15,127}\}$",
        exclude=True,
    )
    system_flag: str | None = Field(
        default=None,
        min_length=22,
        max_length=134,
        pattern=r"^flag\{[A-Za-z0-9][A-Za-z0-9_-]{15,127}\}$",
        exclude=True,
    )

    @model_validator(mode="after")
    def flags_must_be_distinct(self) -> ScenarioDraft:
        if self.user_flag and self.system_flag and self.user_flag == self.system_flag:
            raise ValueError("user_flag and system_flag must be different")
        return self


def scenario_is_valid_for_machine(machine: MachineInformation, scenario: ScenarioDraft) -> bool:
    """Return whether a persisted scenario still matches normalized machine requirements."""

    expected = (
        (machine.needs_user_flag is True, scenario.user_flag, USER_FLAG_VALUE_PATTERN),
        (machine.needs_system_flag is True, scenario.system_flag, SYSTEM_FLAG_VALUE_PATTERN),
    )
    flags_are_valid = all(
        bool(pattern.fullmatch(value or "")) if required else value is None
        for required, value, pattern in expected
    )
    scenario_cves = {
        step.cve_id: step for step in scenario.attack_graph.steps if step.cve_id is not None
    }
    requested_cves_are_grounded = all(
        cve_id in scenario_cves
        and bool(scenario_cves[cve_id].cve_title)
        and bool(scenario_cves[cve_id].cve_description)
        for cve_id in machine.cve_ids
    )
    return flags_are_valid and requested_cves_are_grounded


class ScenarioReviewFinding(BaseModel):
    step_id: str | None = Field(default=None, max_length=128)
    severity: Literal["error", "warning"]
    category: Literal[
        "permission_blocker",
        "permission_shortcut",
        "broken_chain",
        "semantic_mismatch",
        "implementation_gap",
        "unintended_shortcut",
        "acceptance_test_gap",
        "unsupported_assumption",
        "description_spoiler",
        "input_contradiction",
    ]
    repair_target: Literal[
        "scenario_text",
        "attack_graph",
        "attack_graph_regeneration",
        "source_code",
        "user_input",
    ] = "scenario_text"
    repair_fields: list[str] = Field(default_factory=list, max_length=30)
    evidence: str = Field(min_length=1, max_length=4000)
    remediation: str = Field(min_length=1, max_length=4000)

    @model_validator(mode="after")
    def repair_fields_match_target(self) -> ScenarioReviewFinding:
        allowed_graph_fields = {"title", "description", "implementation_steps"}
        allowed_regeneration_fields = {
            "step_id",
            "kind",
            "phase",
            "requires",
            "achieves",
            "cve_id",
            "password_cracking",
        }
        allowed_input_fields = {
            "theme",
            "user_flag_details",
            "system_flag_details",
            "skill_names",
            "cve_ids",
        }
        fields = set(self.repair_fields)
        if self.repair_target == "attack_graph":
            if not fields or not fields <= allowed_graph_fields:
                raise ValueError(
                    "attack_graph repair_fields must only contain title, description, "
                    "or implementation_steps"
                )
        elif self.repair_target == "attack_graph_regeneration":
            if not fields or not fields <= allowed_regeneration_fields:
                raise ValueError(
                    "attack_graph_regeneration repair_fields must contain structural fields"
                )
        elif self.repair_target == "user_input":
            if not fields or not fields <= allowed_input_fields:
                raise ValueError(
                    "user_input repair_fields must identify contradictory machine input fields"
                )
        elif fields:
            raise ValueError(
                f"repair_fields must be empty for repair_target={self.repair_target}"
            )
        if self.repair_target == "user_input" and (
            self.category != "input_contradiction" or self.step_id is not None
        ):
            raise ValueError(
                "user_input is only valid for an explicit input_contradiction without "
                "a generated attack-graph step_id"
            )
        if self.category == "input_contradiction" and self.repair_target != "user_input":
            raise ValueError("input_contradiction findings must target user_input")
        return self


class ScenarioReview(BaseModel):
    approved: bool
    summary: str = Field(min_length=1, max_length=4000)
    findings: list[ScenarioReviewFinding] = Field(default_factory=list, max_length=100)

    @model_validator(mode="after")
    def approval_matches_findings(self) -> ScenarioReview:
        has_error = any(finding.severity == "error" for finding in self.findings)
        if self.approved == has_error:
            raise ValueError("approved must be true exactly when there are no error findings")
        return self


